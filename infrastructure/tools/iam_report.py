"""P5-02: list every IAM role, action and resource in the synthesized stack and flag wildcards.

Usage (from infrastructure/, after `cdk synth`):
    python tools/iam_report.py cdk.out/CloudDocsAI-dev.template.json ../docs/iam-review.md

Wildcards that are known and accepted are explained in ACCEPTED; anything else is reported as
UNREVIEWED and the script exits 1, so a new wildcard can't slip in unnoticed.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

# (role logical-id fragment, action) -> why the wildcard is acceptable
ACCEPTED = {
    ("CDKBucketDeployment", "cloudfront:CreateInvalidation"): "CDK's site upload helper; it can only clear CDN caches. Runs at deploy time only.",
    ("CDKBucketDeployment", "cloudfront:GetInvalidation"): "Same helper, reads the invalidation it created.",
    ("Chat", "bedrock:InvokeModel"): "Region wildcard only (the APAC inference profile routes across APAC Regions); the model ARN is fixed to amazon.nova-lite-v1:0.",
}


def text(v: object) -> str:
    """Render a CloudFormation value (string, Ref, Fn::GetAtt, Fn::Join) readably."""
    if isinstance(v, str):
        return v
    if isinstance(v, dict):
        if "Ref" in v:
            return f"${{{v['Ref']}}}"
        if "Fn::GetAtt" in v:
            return f"${{{'.'.join(v['Fn::GetAtt'])}}}"
        if "Fn::Join" in v:
            sep, parts = v["Fn::Join"]
            return sep.join(text(p) for p in parts)
    if isinstance(v, list):
        return ", ".join(text(x) for x in v)
    return json.dumps(v)


def short(name: str) -> str:
    return re.sub(r"[0-9A-F]{8,}$", "", name)


def main() -> int:
    template = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    out = Path(sys.argv[2])
    res = template["Resources"]
    roles = {k: v for k, v in res.items() if v["Type"] == "AWS::IAM::Role"}
    rows, unreviewed = [], []
    for role_id, role in sorted(roles.items()):
        trust = role["Properties"]["AssumeRolePolicyDocument"]["Statement"][0]["Principal"]
        managed = [text(m).split("/")[-1] for m in role["Properties"].get("ManagedPolicyArns", [])]
        statements = []
        for pol in res.values():
            if pol["Type"] not in ("AWS::IAM::Policy",):
                continue
            if {"Ref": role_id} in pol["Properties"].get("Roles", []):
                statements += pol["Properties"]["PolicyDocument"]["Statement"]
        for st in role["Properties"].get("Policies", []):
            statements += st["PolicyDocument"]["Statement"]
        for st in statements:
            actions = st["Action"] if isinstance(st["Action"], list) else [st["Action"]]
            resource = text(st.get("Resource"))
            wildcard = resource.strip() == "*" or "::*" in resource or ":*:" in resource or any(a.endswith(":*") for a in actions)
            note = ""
            if wildcard:
                why = next((w for (r, a), w in ACCEPTED.items() if r in role_id and a in actions), None)
                if why:
                    note = f"accepted: {why}"
                else:
                    note = "UNREVIEWED wildcard"
                    unreviewed.append((role_id, actions, resource))
            cond = f" when {json.dumps(st['Condition'])}" if "Condition" in st else ""
            rows.append((short(role_id), text(trust), ", ".join(managed), st.get("Effect", "Allow"), ", ".join(sorted(actions)), resource + cond, note))

    lines = [
        "# IAM review (P5-02)",
        "",
        "Generated by `infrastructure/tools/iam_report.py` from the synthesized template. Re-run it after any infrastructure change.",
        "Deploy-time only roles (CDK helpers) exist while CloudFormation runs; the app's runtime roles are the Lambda and Knowledge Base roles.",
        "",
        "Inherited broad grant: every Lambda role carries AWS's `AWSLambdaBasicExecutionRole` (logs:CreateLogGroup/CreateLogStream/PutLogEvents on `*`).",
        "It only writes CloudWatch logs and is the AWS-managed default; each function's log group is created by the stack with 1-week retention.",
        "",
        f"Roles: **{len(roles)}** · statements: **{len(rows)}** · unreviewed wildcards: **{len(unreviewed)}**",
        "",
        "| Role | Trusted by | Managed policies | Effect | Actions | Resource (and condition) | Wildcard note |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append("| " + " | ".join(c.replace("|", "\\|") for c in r) + " |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(roles)} roles, {len(rows)} statements, {len(unreviewed)} unreviewed wildcards -> {out}")
    for u in unreviewed:
        print("UNREVIEWED:", u)
    return 1 if unreviewed else 0


if __name__ == "__main__":
    sys.exit(main())
